def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else "assets/models"
    os.makedirs(outdir, exist_ok=True)
    for name, spec in MODELS.items():
        spec = dict(spec)
        kind = spec.pop("kind")
        if kind == "cart":
            o = build_cart(spec["w"], spec["h"], spec["d"], spec["r"],
                           spec["lw"], spec["lh"], spec.get("ly", 0.0),
                           spec.get("grip", 0.0),
                           spec.get("corner_cut"), spec.get("notch"),
                           seg=spec.get("seg", 8),
                           brand=spec.get("brand"))
        else:
            o = build_disc(spec["radius"], spec["thickness"],
                           spec["label_radius"], spec.get("hole", 0.55))
        path = os.path.join(outdir, f"{name}.obj")
        o.save(path)
        print(f"{path}: {len(o.v)} verts {len(o.f)} faces")

    with open(os.path.join(outdir, "map.txt"), "w") as fp:
        for sysid, model in sorted(SYSTEM_MAP.items()):
            fp.write(f"{sysid} {model}\n")
    print("wrote map.txt")


if __name__ == "__main__":
    main()
